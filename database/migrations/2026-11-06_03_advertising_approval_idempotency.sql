-- Explicit campaign approval history and Meta publication idempotency.
-- Safe to apply more than once.

alter table public.campanias_publicitarias
    add column if not exists meta_instagram_id text,
    add column if not exists meta_idempotency_key uuid;

create unique index if not exists uq_campanias_meta_idempotency_key
    on public.campanias_publicitarias (meta_idempotency_key)
    where meta_idempotency_key is not null;

create table if not exists public.campaign_approvals (
    aprobacion_id bigint generated by default as identity primary key,
    campania_publicitaria_id bigint not null
        references public.campanias_publicitarias (campania_publicitaria_id) on delete cascade,
    empresa_id bigint not null references public.empresas (empresa_id) on delete cascade,
    accion varchar(20) not null
        check (accion in ('requested', 'approved', 'rejected')),
    actor_user_id uuid,
    comentario varchar(1000),
    snapshot jsonb not null default '{}'::jsonb,
    creado_en timestamptz not null default now()
);

create index if not exists idx_campaign_approvals_campaign
    on public.campaign_approvals (campania_publicitaria_id, creado_en desc);
create index if not exists idx_campaign_approvals_company
    on public.campaign_approvals (empresa_id, creado_en desc);

alter table public.campaign_approvals enable row level security;
revoke all on public.campaign_approvals from anon, authenticated;

notify pgrst, 'reload schema';
